#!/usr/bin/env python3
"""Quant-ladder analysis (M3) + tool-calling analysis (M4).

Reads DB rows:
  run_tag='m3-quant-ladder'  -> bench_family='humaneval-multipl-e'
  run_tag='m4-tool-calling'  -> bench_family='bfcl'
Writes ladder_tools.json + LADDER_TOOLS.md.
"""
import json
import math
import sqlite3
from collections import defaultdict

DB = "file:experiments.sqlite?mode=ro"
QUANT_ORDER = ["UD-IQ2_XXS", "UD-IQ2_M", "UD-Q2_K_XL", "UD-Q3_K_XL",
               "UD-Q4_K_XL", "UD-Q5_K_XL", "UD-Q8_K_XL"]


def ci95(vals):
    n = len(vals)
    if n < 2:
        return None
    m = sum(vals) / n
    sd = math.sqrt(sum((x - m) ** 2 for x in vals) / (n - 1))
    se = sd / math.sqrt(n)
    return {"n": n, "mean": round(m, 4), "ci_low": round(m - 1.96 * se, 4),
            "ci_high": round(m + 1.96 * se, 4)}


def q(con, sql):
    return [dict(zip([d[0] for d in con.execute(sql).description], r))
            for r in con.execute(sql)]


def main():
    con = sqlite3.connect(DB, uri=True)
    out = {}

    # ---------- M3: quant ladder ----------
    rows = q(con, """SELECT language, __quant, _score, __size FROM experiments
                     WHERE run_tag='m3-quant-ladder' AND _score IS NOT NULL""")
    grid = defaultdict(dict)          # quant -> lang -> score
    for r in rows:
        grid[r["__quant"]][r["language"]] = r["_score"]
    levels = [x for x in QUANT_ORDER if x in grid]
    out["ladder"] = {
        "levels": levels,
        "per_language": {lvl: grid[lvl] for lvl in levels},
        "pooled_mean": {lvl: round(sum(grid[lvl].values()) / len(grid[lvl]), 4)
                        for lvl in levels},
    }
    step = {}
    for a, b in zip(levels, levels[1:]):
        langs = set(grid[a]) & set(grid[b])
        d = [grid[b][l] - grid[a][l] for l in langs]
        if d:
            step[f"{a}->{b}"] = ci95(d)
    out["ladder"]["steps"] = step

    # ---------- M4/M4b: tool calling (per category, per mode) ----------
    trows = q(con, """SELECT model, _bench, _score, protocol FROM experiments
                      WHERE bench_family='bfcl' AND _score IS NOT NULL""")
    tgrid = defaultdict(dict)
    mode_of = {}
    for r in trows:
        key = f"{r['model']} | {'native' if 'native' in (r['protocol'] or '') else 'forced'}"
        mode_of[key] = 'native' if 'native' in (r['protocol'] or '') else 'forced'
        tgrid[key][r["_bench"].replace("bfcl-", "")] = r["_score"]
    cats = sorted({c for m in tgrid for c in tgrid[m]})
    out["tools"] = {m: tgrid[m] for m in tgrid}
    out["tools_categories"] = cats
    out["tools_mode"] = mode_of
    tsteps = {}
    for key in sorted(tgrid):
        base = key.split(" | ")[0]
        for other in sorted(tgrid):
            ob = other.split(" | ")[0]
            if other == key or ob.rsplit("-", 1)[0] != base.rsplit("-", 1)[0]:
                continue
            if not ("Q2" in base and "Q3" in ob) or mode_of[other] != mode_of[key]:
                continue
            shared = set(tgrid[key]) & set(tgrid[other])
            if shared:
                tsteps[f"{ob} vs {base} ({mode_of[key]})"] = {
                    c: round(tgrid[other][c] - tgrid[key][c], 4) for c in sorted(shared)}
    out["tools_steps"] = tsteps

    with open("ladder_tools.json", "w") as f:
        json.dump(out, f, indent=1)

    # ---------- markdown ----------
    L = ["# Quant ladder (M3) and tool calling (M4)\n",
         "_Auto-generated by `ladder_analysis.py` from the DB._\n",
         "## Weight-quant ladder — Qwen3.5-2B, MultiPL-E\n"]
    if levels:
        langs = sorted({l for lvl in levels for l in grid[lvl]})
        L.append("| quant | " + " | ".join(langs) + " | pooled |")
        L.append("|---|" + "---|" * (len(langs) + 1))
        for lvl in levels:
            cells = [str(round(grid[lvl].get(l, float('nan')), 3)) for l in langs]
            L.append(f"| {lvl} | " + " | ".join(cells) + " | "
                     f"{out['ladder']['pooled_mean'][lvl]} |")
        L.append("")
        L.append("| step | mean Δ | 95% CI | languages |")
        L.append("|---|---|---|---|")
        for k, v in step.items():
            if v:
                L.append(f"| {k} | {v['mean']:+.4f} | [{v['ci_low']:+.4f}, "
                         f"{v['ci_high']:+.4f}] | {v['n']} |")
        L.append("")
    else:
        L.append("_no M3 rows yet_\n")

    L.append("## Tool calling — BFCL\n")
    cats = out.get("tools_categories") or []
    if out.get("tools") and cats:
        L.append("| model | mode | " + " | ".join(cats) + " |")
        L.append("|---|---|" + "---|" * len(cats))
        for m, d in sorted(out["tools"].items()):
            mode = out.get("tools_mode", {}).get(m, "?")
            L.append(f"| {m.split(' | ')[0]} | {mode} | " + " | ".join(
                str(round(d.get(c, float('nan')), 4)) for c in cats) + " |")
        L.append("")
        for tag, d in out.get("tools_steps", {}).items():
            L.append(f"- **{tag}** per category: "
                     + ", ".join(f"`{k}` {v:+.3f}" for k, v in d.items()))
        L.append("")
        L.append("Two protocols: **forced** (prompt asks for a JSON call) and **native** "
                 "(OpenAI `tools=`; the model decides whether to call). They disagree in "
                 "direction: under *forced* framing the 4B Q2->Q3 step looks like a "
                 "profile flip (abstention up, multi-call composition down); under the "
                 "*native* protocol Q3 is better almost everywhere at both sizes. The "
                 "protocol choice, not quantization, produced the earlier 'flip'. "
                 "Report the mode; never mix them.\n")
    else:
        L.append("_no M4 rows yet_\n")

    with open("LADDER_TOOLS.md", "w") as f:
        f.write("\n".join(L) + "\n")
    print(json.dumps({k: v for k, v in out.items()}, indent=1)[:2000])
    print("wrote ladder_tools.json + LADDER_TOOLS.md")


if __name__ == "__main__":
    main()
