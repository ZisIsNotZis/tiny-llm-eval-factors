#!/usr/bin/env python3
"""Generate WRAPUP.md from the wrap-up artifacts.

Reads: resolution.json, archive_manifest.json, claims_ledger.csv,
       .wrapup/w1_summary.jsonl (repeat-noise experiment, if present)
Writes: WRAPUP.md
"""
import csv
import json
import math
import os
from collections import Counter

W1 = ".wrapup/w1_summary.jsonl"


def load_json(p, default=None):
    try:
        with open(p) as f:
            return json.load(f)
    except Exception:
        return default


def w1_stats():
    if not os.path.exists(W1):
        return None
    rows = []
    with open(W1) as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    if not rows:
        return None
    by = {}
    for r in rows:
        if r.get("score") is None:
            continue
        by.setdefault((r["bench"], r["temp"]), []).append(r["score"])
    out = {}
    for k, v in by.items():
        if len(v) < 2:
            out[f"{k[0]}@temp{k[1]}"] = {"n": len(v), "scores": v, "sd": None}
            continue
        m = sum(v) / len(v)
        sd = math.sqrt(sum((x - m) ** 2 for x in v) / (len(v) - 1))
        out[f"{k[0]}@temp{k[1]}"] = {"n": len(v), "mean": round(m, 4),
                                     "sd": round(sd, 4),
                                     "range": round(max(v) - min(v), 4),
                                     "scores": v}
    return out


def mde_items(mde):
    return (1.96 * 2 * math.sqrt(0.25) / mde) ** 2


def w2_stats():
    path = ".wrapup/w2_summary.jsonl"
    if not os.path.exists(path):
        return None
    rows = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    if not rows:
        return None
    by = {}
    for r in rows:
        if r.get("score") is None:
            continue
        by.setdefault(r["model"], []).append(r["score"])
    out = {}
    for m, v in by.items():
        mean = sum(v) / len(v)
        sd = (math.sqrt(sum((x - mean) ** 2 for x in v) / (len(v) - 1))
              if len(v) > 1 else None)
        out[m] = {"n": len(v), "mean": round(mean, 4),
                  "sd": round(sd, 4) if sd is not None else None,
                  "scores": [round(x, 4) for x in v]}
    return out


def multipl_e_panel():
    m = load_json("multipl_e.json", None)
    return m


def main():
    res = load_json("resolution.json", {})
    man = load_json("archive_manifest.json", {})
    ledger = list(csv.DictReader(open("claims_ledger.csv"))) if os.path.exists("claims_ledger.csv") else []
    counts = Counter(r["status"] for r in ledger) if ledger else Counter()
    w1 = w1_stats()

    t = res.get("thresholds", {})
    repeat = t.get("repeat_floor")
    mde_he = t.get("single_pair_humaneval")
    mde_mbpp = t.get("single_pair_mbpp")

    L = []
    L.append("# Wrap-up: what this study actually established\n")
    L.append("_Auto-generated by `build_wrapup.py`. Companion files: `resolution.md`, "
             "`CLAIMS_RESOLUTION.md`, `ARCHIVE_MANIFEST.md`, `claims_ledger.csv`._\n")

    L.append("## TL;DR\n")
    L.append("- The study is **an effect-estimation study, not a predictor**. It produces "
             "controlled local contrasts and negative results; the pooled formula loses to a "
             "plain ridge once a whole architecture is held out (family RMSE 0.294 vs 0.282).")
    L.append(f"- The headline methodological result: **only {counts.get('resolved',0)} of "
             f"{len(ledger)} documented claims clear their own noise floor.** "
             f"{counts.get('unauditable',0)} are unauditable (they depend on variables absent "
             f"from the DB schema), and most of the rest are model-fit statements, not effects.")
    L.append(f"- Root cause is **item count, not difficulty**: HumanEval+MBPP give 542 items, "
             f"so a single-config *capability* effect below **~0.084** cannot be resolved, "
             f"however many times you rerun it.")
    L.append("- The dataset is **frozen and no longer reproducible end-to-end**: "
             f"{man.get('models_present')}/{man.get('models_referenced')} model files "
             f"({man.get('model_coverage_pct')}%) and "
             f"{man.get('eval_results_recovered')}/{man.get('db_rows')} raw eval results "
             f"({man.get('eval_results_coverage_pct')}%) survive.\n")

    L.append("## 1. Resolution floors (why most claims are not evidence)\n")
    L.append("| floor | value | meaning |")
    L.append("|---|---|---|")
    L.append(f"| repeat floor (measured) | {repeat} | same config, same items → reproducibility |")
    L.append(f"| item floor, HumanEval | {res.get('thresholds',{}).get('item_floor_humaneval')} | 164 items sample capability |")
    L.append(f"| item floor, MBPP | {res.get('thresholds',{}).get('item_floor_mbpp')} | 378 items |")
    L.append("")
    L.append(f"A single matched pair can only resolve |Δ| ≳ **{mde_he}** on HumanEval / "
             f"**{mde_mbpp}** on MBPP. Almost every single-pair delta in `conclusions.md` is "
             "below this. Aggregates (44+ contexts) survive; single pairs mostly do not.\n")
    L.append("> The earlier report figure of an *irreducible floor ≈ 0.088* is unsourced; "
             "no data cell reproduces it. See `resolution.md`.\n")

    L.append("## 2. Measured run-to-run noise (W1)\n")
    if w1:
        L.append("Frozen protocol: `Qwen3.5-2B-UD-Q4_K_XL`, ctx 2048, KV `q8_0/q8_0`, "
                 "`top_p 0.95 / top_k 40 / min_p 0.05`, repeated N times.\n")
        L.append("| condition | n | mean | sd | range |")
        L.append("|---|---|---|---|---|")
        for k, v in sorted(w1.items()):
            if v.get("sd") is None:
                L.append(f"| {k} | {v['n']} | — | — | — |")
            else:
                L.append(f"| {k} | {v['n']} | {v['mean']} | **{v['sd']}** | {v['range']} |")
        L.append("")
        L.append("This is the measurement the original study never had: the DB contains **zero** "
                 "replicates, so run stochasticity was previously assumed, not measured.\n")
    else:
        L.append("_W1 repeat experiment not finished; see `.wrapup/w1_summary.jsonl`._\n")

    L.append("## 3. Items, not difficulty: the resource that would actually help\n")
    L.append("| target MDE | items needed |")
    L.append("|---|---|")
    for mde in (0.10, 0.08, 0.05, 0.03):
        L.append(f"| {mde} | ~{mde_items(mde):,.0f} |")
    L.append("")
    L.append(f"- current HumanEval+MBPP = 542 items → MDE ≈ {1.96*2*math.sqrt(0.25/542):.3f}")
    L.append(f"- MultiPL-E (18 languages × 164) = 2952 items → MDE ≈ {1.96*2*math.sqrt(0.25/2952):.3f}")
    L.append(f"- BigCodeBench = 1140 items → MDE ≈ {1.96*2*math.sqrt(0.25/1140):.3f}")
    L.append("")
    L.append("**Conclusion:** the fix is *more items at similar difficulty* (MultiPL-E), not a "
             "harder benchmark. BigCodeBench/SWE-style tasks would floor this panel "
             "(0.2B–9B models) at ~0 and are also compute-hostile; Terminal-Bench is worse. "
             "They are construct-validity anchors, not measurement instruments.\n")

    L.append("## 4. Headline claim re-check (`reanalysis.py`)\n")
    ra = load_json("reanalysis.json", {})
    if ra:
        bra = ra.get("bad_rate_audit", {})
        L.append(f"- **The flagship \"reasoning collapses output validity\" result is falsified as "
                 f"stated.** Of {bra.get('rows_bad_ge_0.5')} rows with `bad_rate>=0.5`, "
                 f"**{bra.get('of_which_chaotic_sampling')}** come from the chaotic random-sampling "
                 f"sweep. Under clean decoding, `auto` bad_rate = "
                 f"{bra.get('clean_reasoning_auto_mean_bad')} vs `off` = "
                 f"{bra.get('clean_reasoning_off_mean_bad')}.")
        mr = ra.get("matched_reasoning_clean", {})
        for b, v in mr.items():
            d = v["d_score_off_minus_auto"]
            L.append(f"- Matched reasoning (`off−auto`, {b}): **{d['mean']:+.3f}** "
                     f"CI [{d['ci_low']:+.3f}, {d['ci_high']:+.3f}], n={d['n']} — real and large, "
                     f"but family-conditioned (Qwen3.6-dominated).")
        mq = ra.get("matched_weight_quant", {})
        if mq:
            L.append("- Matched weight-quant step (the most reproducible effect family):")
            for k, v in sorted(mq.items()):
                L.append(f"  - `{k}`: **{v['mean']:+.3f}** CI [{v['ci_low']:+.3f}, "
                         f"{v['ci_high']:+.3f}], n={v['n']}")
        dup = ra.get("duplicates", {})
        L.append(f"- Duplicate audit: {dup.get('groups')} groups differ only in "
                 f"`spec_draft_n_max` ({dup.get('extra_rows')} rows); "
                 f"{dup.get('by_spec_type')}.")
        L.append("")

    L.append("## 5. Scale-generalisation ladder (W2)\n")
    w2 = w2_stats()
    if w2:
        L.append("Restored Q2/Q3 weights, frozen protocol (ctx 2048, KV `q8_0/q8_0`, greedy), "
                 "HumanEval, 2 repeats per checkpoint. Tests whether the local weight-quant "
                 "step survives a scale increase.\n")
        L.append("| checkpoint | n | mean pass@1_plus | sd |")
        L.append("|---|---|---|---|")
        for m, v in sorted(w2.items()):
            L.append(f"| {m} | {v['n']} | {v['mean']} | {v['sd']} |")
        L.append("")
        for fam, q2, q3 in (("Qwen3.5-9B", "qwen9b-q2", "qwen9b-q3"),
                            ("Qwen3.5-4B", "qwen4b-q2", "qwen4b-q3")):
            if q2 in w2 and q3 in w2:
                d = w2[q3]["mean"] - w2[q2]["mean"]
                L.append(f"- **{fam} Q2→Q3**: {d:+.3f} "
                         f"({w2[q2]['mean']} → {w2[q3]['mean']})")
        L.append("")
        L.append("Each point is a greedy run, which W1 shows is exactly deterministic, so these "
                 "means carry no run noise — only the item-sampling floor (~0.039) applies.\n")
        L.append("> **Superseded by §6.** The 9B reversal here does not replicate under the "
                 "MultiPL-E raw-completion protocol (9B `+0.143` there), so it is a "
                 "protocol×quantization artifact at 9B, not a scale effect.\n")
    else:
        L.append("_W2 ladder not finished; see `.wrapup/w2_summary.jsonl`._\n")

    L.append("## 6. MultiPL-E resolution panel (the item-count fix)\n")
    me = multipl_e_panel()
    if me and me.get("families"):
        mpl_rows = me.get("n_rows")
        L.append(f"Ran the weight-quant step across languages **and model families** to attack "
                 f"the item-count bottleneck directly ({mpl_rows} runs; "
                 f"`multipl_e.json`/`MULTIPLE.md`). Raw completion, greedy; each language is "
                 f"~161 fresh items.\n")
        L.append("_(per-family ladders are in `MULTIPLE.md`; the headline is below)_\n")
        s = me.get("Q2_Q3_family_summary") or {}
        if s:
            L.append(f"**Cross-family `Q2→Q3` (the core effect): {s['n_families']} model anchors, "
                     f"all sign-consistent, range {s['min']:+.3f} .. {s['max']:+.3f}, "
                     f"mean {s['mean']:+.3f}.**\n")
        L.append("| model anchor | Q2→Q3 | 95% CI |")
        L.append("|---|---|---|")
        for f, v in sorted((me.get("Q2_Q3_by_family") or {}).items()):
            if v:
                L.append(f"| {f} | **{v['mean']:+.4f}** | [{v['ci_low']:+.4f}, {v['ci_high']:+.4f}] |")
        L.append("")
        L.append("The `Q2→Q3` step is the study's one firmly established quantitative result: "
                 "it is positive in **every** language and **every** architecture family tested "
                 "(Qwen3.5 at 2B/4B/9B, gemma-4 at E2B/E4B, granite-4.1-3b).\n")
    else:
        L.append("_MultiPL-E panel not finished; see `.wrapup/m1_summary.jsonl`._\n")

    L.append("## 7. Quant ladder + tool calling (M3 / M4)\n")
    lt = load_json("ladder_tools.json", None)
    if lt and lt.get("ladder", {}).get("levels"):
        lad = lt["ladder"]
        L.append("### 7a. Where does the quant curve saturate? (`Qwen3.5-2B`, MultiPL-E)\n")
        langs = sorted({l for lv in lad["levels"] for l in lad["per_language"][lv]})
        L.append("| quant | " + " | ".join(langs) + " | pooled |")
        L.append("|---|" + "---|" * (len(langs) + 1))
        for lv in lad["levels"]:
            cells = [str(round(lad["per_language"][lv].get(l, float('nan')), 3)) for l in langs]
            L.append(f"| {lv} | " + " | ".join(cells) + f" | {lad['pooled_mean'][lv]} |")
        L.append("")
        L.append("| step | mean Δ | 95% CI | langs |")
        L.append("|---|---|---|---|")
        for k, v in lad.get("steps", {}).items():
            if v:
                L.append(f"| {k} | {v['mean']:+.4f} | [{v['ci_low']:+.4f}, {v['ci_high']:+.4f}] | {v['n']} |")
        L.append("")
        L.append("> **Answer to \"should we run Q4/Q5?\"** — yes, and the result is that there is "
                 "**no effect above Q3**: the one meaningful step is `Q2->Q3`, IQ2≈Q2, and "
                 "Q3≈Q4≈Q5. The operational rule is simply \">= Q3\".\n")
    if lt and lt.get("tools"):
        L.append("### 7b. Tool calling (BFCL, prompt mode, thinking off)\n")
        cats = lt.get("tools_categories") or []
        L.append("| model | " + " | ".join(cats) + " |")
        L.append("|---|" + "---|" * len(cats))
        for m, d in sorted(lt["tools"].items()):
            L.append(f"| {m} | " + " | ".join(
                f"{d.get(c, float('nan')):.4f}" for c in cats) + " |")
        L.append("")
        for tag, d in (lt.get("tools_steps") or {}).items():
            L.append(f"- **{tag}** per category: "
                     + ", ".join(f"`{k}` {v:+.3f}" for k, v in d.items()))
        L.append("")
        L.append("Aggregate BFCL hides opposing effects: at 4B, Q2 and Q3 tie overall "
                 "(+0.02) while abstention improves (+0.42 irrelevance) and multi-call "
                 "composition collapses (-0.29 parallel_multiple). At 2B, aggressive "
                 "quantisation is devastating for tool use (parallel 0.055 at Q2 vs 0.625 "
                 "at Q3). Tool calling is more quant-sensitive at small scale than code is.\n")
    else:
        L.append("_M4 tool-calling panel not finished; see `.wrapup/m4_summary.jsonl`._\n")

    L.append("## 8. What was added / recovered during wrap-up\n")
    L.append("- `resolution.py` / `resolution.json` / `resolution.md` — measured resolution floors.")
    L.append("- `claims_ledger.py` / `claims_ledger.csv` / `CLAIMS_RESOLUTION.md` — every claim tagged.")
    L.append("- `archive_manifest.py` / `archive_manifest.json` / `ARCHIVE_MANIFEST.md` — evidence inventory.")
    L.append("- `.wrapup/run_w1.sh` — repeat-noise experiment.")
    L.append("- `reanalysis.py` / `reanalysis.json` / `REANALYSIS.md` — strict re-check of headline claims.")
    L.append("- `mpl_run.py` + `.wrapup/run_m1.sh` / `run_m2.sh` — MultiPL-E generation + execution harness.")
    L.append("- `multipl_e_analysis.py` / `multipl_e.json` / `MULTIPLE.md` — cross-language panel.")
    L.append("- `ladder_analysis.py` / `ladder_tools.json` / `LADDER_TOOLS.md` — quant ladder (M3) + BFCL (M4).")
    L.append("- `.wrapup/bfcl_run.py` + `run_m3.sh` / `run_m4.sh` — tool-calling and quant-ladder harnesses.")
    L.append("- `migrate_db.py` — schema upgrade (replicates enabled) + ingestion of W1/W2/M1/M2/M3/M4.")
    L.append("- Model weights re-fetched via **ModelScope** (HF direct + hf-mirror are intermittently "
             "blocked here): `Qwen3.5-2B/4B/9B` Q2/Q3, `gemma-4-E4B` Q3.")
    L.append("- EvalPlus datasets (`HumanEvalPlus`, `MbppPlus`) re-fetched via GitHub / ghfast.top proxy.\n")

    L.append("## 9. Provenance warnings (read before citing any number)\n")
    L.append(f"DB schema is missing nothing essential now: `migrate_db.py` added "
             "`run_tag, rep, ctx_size, parallel_slots, seed, protocol, language, "
             "bench_family, max_tokens, source_file, completed_at` and **removed the unique "
             "index that forbade replicates**.")
    L.append("- Legacy rows still predate those columns (ctx/parallel/seed are NULL), so their "
             "`ctx=`/`parallel=` scopes remain unauditable.")
    L.append("- No `seed` column → run-to-run stochasticity was unmeasured until W1.")
    L.append("- Raw artifacts map to rows only by timestamp; legacy hash collisions were "
             "previously confirmed, so coefficient slices from old sweeps are lower-confidence.")
    L.append("- Exact-score ties across models are **not** duplication evidence (the k/164 grid "
             "produces them; observed ties are *below* the shuffled null).\n")

    L.append("## 10. Status of the knowledge base\n")
    L.append("| status | claims |")
    L.append("|---|---|")
    for k in ("resolved", "underpowered", "noise_level", "unauditable", "model_fit", "qualitative"):
        if counts.get(k):
            L.append(f"| {k} | {counts[k]} |")
    L.append("")
    L.append("`resolved` = survives the noise floor. `underpowered` = plausible but not "
             "established at this item count. `unauditable` = cannot be checked against the DB.\n")

    L.append("## 11. Blocked / closed items\n")
    L.append("- **EvalPerf** — needs `perf_event_paranoid` change; `=4` here. Closed.")
    L.append("- **35B strict same-scale family anchor** — OOM on 24 GB. Closed (9B/12B used as "
             "degraded substitutes instead).")
    L.append("- **Automated fixed-loop sweeps** — disallowed by policy. Closed.")
    L.append("- **Terminal-Bench / SWE-bench as a data source** — too slow / Docker-heavy; only "
             "ever usable as a handful of qualitative anchors.\n")

    with open("WRAPUP.md", "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote WRAPUP.md")
    print(f"claims: {dict(counts)}")
    if w1:
        print("W1:", json.dumps({k: {kk: vv for kk, vv in v.items() if kk != 'scores'}
                                 for k, v in w1.items()}, indent=1))


if __name__ == "__main__":
    main()
