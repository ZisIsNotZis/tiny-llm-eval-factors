#!/usr/bin/env python3
"""Join PPL (T1) with pass@1 (existing DB) to explain the ">= Q3 is enough" paradox.

Reads:
  .wrapup/ppl_summary.jsonl     -> {"model","quant","corpus","ppl","n_chunks","ctx"}
  experiments.sqlite            -> MultiPL-E pass@1 by (base model, quant level)

Writes PPL_JOIN.md + ppl_join.json

The point: show, per anchor and quant level, whether PPL keeps improving *above* the
level where pass@1 stops improving.  If yes, the ">= Q3" rule is a statement about
benchmark sensitivity, not about model quality.
"""
import json
import math
import os
import re
import sqlite3
from collections import defaultdict

PPL = ".wrapup/ppl_summary.jsonl"
DB = "file:experiments.sqlite?mode=ro"
QUANT_RE = re.compile(r"-((UD-)?I?Q[1-8][A-Z0-9_]*)\.gguf$", re.I)
LEVEL_RE = re.compile(r"(?:I)?Q([1-8])", re.I)


def level_of(q):
    m = LEVEL_RE.search(q or "")
    return int(m.group(1)) if m else None


def base_of(model):
    return QUANT_RE.sub("", model).rstrip("-.")


def load_ppl():
    if not os.path.exists(PPL):
        return []
    rows = []
    with open(PPL) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                rows.append(json.loads(line))
            except Exception:
                pass
    return rows


def load_scores():
    con = sqlite3.connect(DB, uri=True)
    # Frozen greedy ladder only: sampling rows (m27) carry a temp-tagged
    # protocol and must not be averaged into a quant cell (SSOT: no protocol mix).
    q = """SELECT model, __quant, language, _score FROM experiments
           WHERE bench_family='humaneval-multipl-e' AND _score IS NOT NULL
             AND protocol='multipl-e-raw-greedy-768'"""
    grid = defaultdict(list)
    for model, quant, lang, score in con.execute(q):
        grid[(base_of(model), quant)].append(score)
    return {k: sum(v) / len(v) for k, v in grid.items()}


def verdict(levels):
    """levels: list of (lv, ppl, score or None), ordered by lv."""
    pts = [p for p in levels if p[1] is not None]
    if len(pts) < 2:
        return {}
    # lowest PPL = best; find where score stops improving (within 0.01)
    best_score = max((p[2] for p in pts if p[2] is not None), default=None)
    if best_score is None:
        return {}
    sat = 1
    for lv, ppl, sc in pts:
        if sc is not None and sc >= best_score - 0.01:
            sat = lv
            break
    # does PPL still improve above sat?
    above = [p for p in pts if p[0] > sat]
    ppl_still_improves = False
    if above:
        ref = [p[1] for p in pts if p[0] == sat]
        if ref and min(p[1] for p in above) < ref[0] - 1e-6:
            ppl_still_improves = True
    return {"score_saturates_at_level": sat,
            "max_score": round(best_score, 4),
            "ppl_improves_above_saturation": ppl_still_improves}


def main():
    ppl_rows = load_ppl()
    scores = load_scores()
    if not ppl_rows:
        print("no .wrapup/ppl_summary.jsonl yet — run T1 first")
        return

    # group: anchor -> quant -> corpus -> ppl
    by_anchor = defaultdict(lambda: defaultdict(dict))
    for r in ppl_rows:
        anchor = base_of(r["model"])
        by_anchor[anchor][r["quant"]][r.get("corpus", "?")] = r.get("ppl")

    out = {}
    for anchor, quants in by_anchor.items():
        levels = []
        for q, corpora in quants.items():
            lv = level_of(q)
            ppl = min(v for v in corpora.values() if v is not None) if any(
                v is not None for v in corpora.values()) else None
            sc = scores.get((anchor, q))
            levels.append((lv, ppl, sc))
        levels = [x for x in levels if x[0] is not None]
        levels.sort()
        out[anchor] = {
            "levels": [{"level": lv, "ppl": ppl, "pass_at_1": (round(s, 4) if s is not None else None)}
                       for lv, ppl, s in levels],
            "verdict": verdict(levels),
        }

    with open(".wrapup/out/ppl_join.json", "w") as f:
        json.dump(out, f, indent=1)

    L = ["# PPL vs pass@1: why does \">= Q3\" look sufficient?\n",
         "_Auto-generated by `ppl_analysis.py` (T1 join)._\n"]
    for anchor, d in sorted(out.items()):
        L.append(f"## {anchor}\n")
        L.append("| quant level | PPL | pass@1 (MultiPL-E) |")
        L.append("|---|---|---|")
        for lv in d["levels"]:
            p = f"{lv['ppl']:.4f}" if lv["ppl"] is not None else "—"
            s = f"{lv['pass_at_1']:.4f}" if lv["pass_at_1"] is not None else "—"
            L.append(f"| Q{lv['level']} | {p} | {s} |")
        v = d["verdict"]
        if v:
            L.append("")
            L.append(f"- score is saturated from **Q{v['score_saturates_at_level']}** "
                     f"(max {v['max_score']})")
            L.append(f"- PPL still improves above that point: "
                     f"**{v['ppl_improves_above_saturation']}**")
        L.append("")
    with open(".wrapup/out/PPL_JOIN.md", "w") as f:
        f.write("\n".join(L) + "\n")
    print(json.dumps(out, indent=1)[:3000])
    print("wrote ppl_join.json + PPL_JOIN.md")


if __name__ == "__main__":
    main()
